//! The LV2 bundle's Turtle files, generated from [`crate::VARIANTS`] so the
//! port lists can never drift from the code. A test checks the files in
//! `lv2/sgv2.lv2/` against this output.

use crate::{Role, VARIANTS};
use sgv2_core::voicing::buzz::{BufferMode, HOST_HOP};
use std::fmt::Write;

fn uri(v: &str) -> &str {
    v.trim_end_matches('\0')
}

pub fn generate() -> (String, String) {
    let mut m = String::new();
    m.push_str("@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n");
    m.push_str("@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n");
    m.push_str("\n# Generated by `cargo run -p sgv2-lv2 --example gen-ttl`; do not edit.\n");
    for (u, ..) in VARIANTS {
        let _ = write!(
            m,
            "\n<{}>\n    a lv2:Plugin ;\n    lv2:binary <libsgv2_lv2.so> ;\n    rdfs:seeAlso <sgv2.ttl> .\n",
            uri(u)
        );
    }

    let mut p = String::new();
    p.push_str("@prefix doap: <http://usefulinc.com/ns/doap#> .\n");
    p.push_str("@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n");
    p.push_str("@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n");
    p.push_str("\n# Generated by `cargo run -p sgv2-lv2 --example gen-ttl`; do not edit.\n");
    for &(u, n, s, role) in VARIANTS {
        let name = match (role, s) {
            (Role::Placeholder, _) => format!("sgv2 placeholder, test only ({n} channels, {s} sense)"),
            (Role::Protect, 0) => format!("sgv2 speaker protection ({n} channels)"),
            (Role::Protect, _) => format!("sgv2 speaker protection ({n} channels, {s} sense)"),
        };
        let _ = write!(
            p,
            "\n<{}>\n    a lv2:Plugin, lv2:UtilityPlugin ;\n    doap:name \"{}\" ;\n    doap:license <https://opensource.org/licenses/MIT> ;\n    lv2:optionalFeature lv2:hardRTCapable ;\n    lv2:port ",
            uri(u),
            name
        );
        let mut ports = Vec::new();
        for c in 0..n {
            ports.push(format!(
                "[\n        a lv2:AudioPort, lv2:InputPort ; lv2:index {c} ; lv2:symbol \"in_{c}\" ; lv2:name \"In {c}\"\n    ]"
            ));
        }
        for c in 0..n {
            ports.push(format!(
                "[\n        a lv2:AudioPort, lv2:OutputPort ; lv2:index {} ; lv2:symbol \"out_{c}\" ; lv2:name \"Out {c}\"\n    ]",
                n + c
            ));
        }
        for k in 0..s {
            ports.push(format!(
                "[\n        a lv2:AudioPort, lv2:InputPort ; lv2:index {} ; lv2:symbol \"sense_{k}\" ; lv2:name \"Sense {k}\"\n    ]",
                2 * n + k
            ));
        }
        let b = 2 * n + s;
        ports.push(format!(
            "[\n        a lv2:ControlPort, lv2:OutputPort ; lv2:index {b} ; lv2:symbol \"latency\" ; lv2:name \"Latency\" ;\n        lv2:designation lv2:latency ; lv2:portProperty lv2:reportsLatency, lv2:integer\n    ]"
        ));
        ports.push(format!(
            "[\n        a lv2:ControlPort, lv2:OutputPort ; lv2:index {} ; lv2:symbol \"health\" ; lv2:name \"Health\" ;\n        lv2:portProperty lv2:integer\n    ]",
            b + 1
        ));
        ports.push(format!(
            "[\n        a lv2:ControlPort, lv2:OutputPort ; lv2:index {} ; lv2:symbol \"sense_delay\" ; lv2:name \"Sense delay\" ;\n        lv2:portProperty lv2:integer\n    ]",
            b + 2
        ));
        p.push_str(&ports.join(" , "));
        p.push_str(" .\n");
    }
    for &(u, n, mode) in crate::voicing::VARIANTS {
        let _ = write!(
            m,
            "\n<{}>\n    a lv2:Plugin ;\n    lv2:binary <libsgv2_lv2.so> ;\n    rdfs:seeAlso <sgv2.ttl> .\n",
            uri(u)
        );
        let name = if mode == BufferMode::Staged {
            format!("sgv2 voicing, staged buffers ({n} lanes)")
        } else {
            format!("sgv2 voicing ({n} lanes)")
        };
        let _ = write!(
            p,
            "\n<{}>\n    a lv2:Plugin, lv2:UtilityPlugin ;\n    doap:name \"{name}\" ;\n    doap:license <https://opensource.org/licenses/MIT> ;\n",
            uri(u)
        );
        if mode == BufferMode::Staged {
            let _ = writeln!(
                p,
                "    rdfs:comment \"Buffer-invariant transport for variable host callbacks; adds {HOST_HOP} frames to the processing latency reported by the voicing chain.\" ;"
            );
        }
        p.push_str("    lv2:optionalFeature lv2:hardRTCapable ;\n    lv2:port ");
        let mut ports = Vec::new();
        for c in 0..2 {
            ports.push(format!(
                "[ a lv2:AudioPort, lv2:InputPort ; lv2:index {c} ; lv2:symbol \"in_{c}\" ; lv2:name \"In {c}\" ]"
            ));
        }
        for c in 0..n {
            ports.push(format!(
                "[ a lv2:AudioPort, lv2:OutputPort ; lv2:index {} ; lv2:symbol \"out_{c}\" ; lv2:name \"Out {c}\" ]",
                c + 2
            ));
        }
        ports.push(format!("[ a lv2:ControlPort, lv2:InputPort ; lv2:index {} ; lv2:symbol \"volume\" ; lv2:name \"Volume\" ; lv2:default 1 ; lv2:minimum 0 ; lv2:maximum 1 ]", n+2));
        ports.push(format!("[ a lv2:ControlPort, lv2:InputPort ; lv2:index {} ; lv2:symbol \"volume_db\" ; lv2:name \"Volume dB override (1 = automatic)\" ; lv2:default 1 ; lv2:minimum -200 ; lv2:maximum 1 ]", n+3));
        ports.push(format!("[ a lv2:ControlPort, lv2:OutputPort ; lv2:index {} ; lv2:symbol \"health\" ; lv2:name \"Health\" ; lv2:portProperty lv2:integer ]", n+4));
        p.push_str(&ports.join(" ,\n    "));
        p.push_str(" .\n");
    }
    (m, p)
}
