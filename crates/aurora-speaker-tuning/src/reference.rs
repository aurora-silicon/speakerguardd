//! macOS 26.6.2 (25G83) is the reference (Ryan, 2026-11-09): v2's engine
//! implements 25G83's laws. A Mac on any macOS build whose speaker tuning for
//! its AID is byte-identical to 25G83's (the speaker strips and property
//! strips, the protection sidecars, the speaker graphs and `Config/AID<n>.plist`;
//! microphone, ADM and DSP-database files are not part of it) is treated as
//! 25G83: compiled with 25G83's laws and checked against the 25G83 parity
//! block. Anything else keeps its own build, and needs that build's block.
//!
//! [`REFERENCE`] holds, per AID, a digest of those files in 25G83 (hashes
//! only, generated by `examples/reference-digests.rs` from the 25G83 Tunings
//! folder; never edited by hand).

use std::collections::BTreeMap;

/// The reference macOS build.
pub const BUILD: &str = "25G83";

/// `{"build": "25G83", "aids": {"AID14": "<sha256>", ...}}`.
const REFERENCE: &str = include_str!("reference-25G83.json");

/// Whether `path` (a bundle path, `AID<n>/...` or `Config/AID<n>.plist`) is one
/// of the files the reference comparison covers for `aid`.
pub fn covered(aid: &str, path: &str) -> bool {
    if path == format!("Config/{aid}.plist") {
        return true;
    }
    let Some(rest) = path.strip_prefix(&format!("{aid}/DSP/")) else { return false };
    let (dir, name) = rest.split_once('/').unwrap_or(("", rest));
    match dir {
        "Strips" => {
            name.starts_with("builtin_speaker_out") || ["spp3", "atsp", "lsm2"].iter().any(|u| name.contains(u))
        }
        "Graphs" => name.starts_with("builtin_speaker_out"),
        _ => false,
    }
}

/// The digest of the covered files among `files` (bundle path -> bytes).
pub fn digest(aid: &str, files: &BTreeMap<String, Vec<u8>>) -> String {
    let mut text = String::from("sgv2 reference digest v1\n");
    for (path, bytes) in files.iter().filter(|(p, _)| covered(aid, p)) {
        text.push_str(&format!("{path}\0{}\n", crate::manifest::sha256_hex(bytes)));
    }
    crate::manifest::sha256_hex(text.as_bytes())
}

/// 25G83's digest for `aid`, if 25G83 has that AID.
pub fn reference_digest(aid: &str) -> Option<String> {
    let v: serde_json::Value = serde_json::from_str(REFERENCE).ok()?;
    v.get("aids")?.get(aid)?.as_str().map(str::to_string)
}

/// The build whose laws and parity block apply to a tuning collected on
/// `macos_build`: [`BUILD`] when its covered files equal 25G83's, else its own.
pub fn law_build(aid: &str, files: &BTreeMap<String, Vec<u8>>, macos_build: Option<&str>) -> Option<String> {
    match reference_digest(aid) {
        Some(r) if r == digest(aid, files) => Some(BUILD.to_string()),
        _ => macos_build.map(str::to_string),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_the_speaker_files_only() {
        assert!(covered("AID14", "AID14/DSP/Strips/builtin_speaker_out_general_3.austrip"));
        assert!(covered("AID14", "AID14/DSP/Strips/aid14-aufx-spp3-appl.plist"));
        assert!(covered("AID14", "AID14/DSP/Graphs/builtin_speaker_out.dspg"));
        assert!(covered("AID14", "Config/AID14.plist"));
        assert!(!covered("AID14", "AID14/DSP/Strips/builtin_microphone_general.austrip"));
        assert!(!covered("AID14", "AID14/DSP/DSPDatabase.plist"));
        assert!(!covered("AID14", "AID14/ADM/config.plist"));
        assert!(!covered("AID14", "AID13/DSP/Graphs/builtin_speaker_out.dspg"));
    }

    #[test]
    fn identical_files_take_the_reference_and_others_keep_their_build() {
        let mut f = BTreeMap::new();
        f.insert("AID99/DSP/Graphs/builtin_speaker_out.dspg".to_string(), b"g".to_vec());
        // no reference digest for AID99: its own build
        assert_eq!(law_build("AID99", &f, Some("26A428")).as_deref(), Some("26A428"));
        // mic files never change the digest
        let d = digest("AID99", &f);
        f.insert("AID99/DSP/Strips/builtin_microphone_voice.austrip".to_string(), b"m".to_vec());
        assert_eq!(digest("AID99", &f), d);
    }
}
