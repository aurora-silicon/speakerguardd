//! Reader and validator for a Mac's own speaker tuning bundle.
//!
//! The Aurora installer copies, read-only, the Mac's `AID<n>` tuning folder
//! (selected by the device tree's `acoustic-id`) and its per-unit
//! `speaker-thiele-small` record into the vendor firmware, with a manifest
//! of sizes and SHA-256 hashes.  This crate finds that bundle, verifies it,
//! and exposes typed, validated data:
//!
//! * [`plist`]: binary (`bplist00`, complete) and XML property lists;
//! * [`aupreset`]: AudioUnit presets and their saved parameter state;
//! * [`strip`]: `.austrip` and `.propstrip`;
//! * [`dspg`]: the graph language (with its macro preprocessor), processing
//!   order and channel-lane tracing;
//! * [`select`]: the DSP database's choice of graph and strip;
//! * [`spp3`]: the spp3 sidecar (OL_thermal, OL_disp, CL, globals);
//! * [`names`]: the specification's parameter-ID maps;
//! * [`spts`]: the factory calibration record;
//! * [`lattice`]: the lsm2 masker's bucket lattice the installer extracts;
//! * [`tuning`]: all of it assembled for the engine and graph generator;
//! * [`units`]: the units-and-semantics table; [`versions`]: macOS releases;
//! * [`compile`]: the protection core's parameter blob, bound to the
//!   [`machine`] it runs on.
//!
//! No Apple data is part of this crate or its tests: fixtures are synthetic
//! and generated by the tests themselves.
//!
//! Module ownership: lane A (tuning reader).  See docs/CONVENTIONS.md.

pub mod aupreset;
